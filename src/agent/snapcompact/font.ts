const GLYPHS = Uint8Array.from(DATA.match(/../g) ?? [], (hex) => Number.parseInt(hex, 16));

/** Row bytes for a code point, or undefined when the font has no glyph for it. */
export function glyphRows(codePoint: number): Uint8Array | undefined {
  let index = 0;
  for (const [first, last] of RANGES) {
    if (codePoint >= first && codePoint <= last) {
      index += codePoint - first;
      return GLYPHS.subarray(index * GLYPH_HEIGHT, (index + 1) * GLYPH_HEIGHT);
    }
    index += last - first + 1;
  }
  return undefined;
}
